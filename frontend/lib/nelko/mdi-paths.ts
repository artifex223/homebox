/** Strips an `mdi:` or `mdi-` prefix and lowercases the slug. */
export function normalizeIconSlug(slug: string | null | undefined): string {
  if (!slug || typeof slug !== "string") return "";
  return slug
    .trim()
    .toLowerCase()
    .replace(/^mdi[:-]/, "");
}

/** Matches an `icon: mdi:<slug>` directive in an entity description. */
export function extractIconDirective(description: string | null | undefined): string | null {
  if (!description) return null;
  const match = description.match(/(?:^|\n)\s*icon:\s*(?:mdi:)?([a-z0-9-]+)/i);
  return match?.[1] ? normalizeIconSlug(match[1]) : null;
}

/**
 * Picks a glyph for an entity, in priority order: explicit override, an
 * `icon: mdi:<slug>` directive in the description, a keyword match on the
 * title, then the type-specific fallback.
 */
export function resolveIcon(
  name = "",
  description = "",
  explicitIcon: string | null = null,
  isLocation = true
): string {
  const explicit = normalizeIconSlug(explicitIcon);
  if (explicit && explicit in MDI_PATHS) return explicit;

  const directive = extractIconDirective(description);
  if (directive && directive in MDI_PATHS) return directive;

  if (name) {
    for (const rule of KEYWORD_RULES) {
      if (rule.pattern.test(name)) return rule.icon;
    }
  }

  return isLocation ? "archive-outline" : "package-variant";
}

/** Returns the 24 x 24 path data for a slug, falling back to the archive glyph. */
export function getIconPath(slug: string | null | undefined): string {
  const normalized = normalizeIconSlug(slug);
  return MDI_PATHS[normalized] ?? MDI_PATHS["archive-outline"];
}

/** Whether a freeform slug typed into the modal resolves to a known glyph. */
export function hasIcon(slug: string | null | undefined): boolean {
  return normalizeIconSlug(slug) in MDI_PATHS;
}
